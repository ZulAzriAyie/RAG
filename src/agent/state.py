"""
The schema for runtime state and Pydantic validation models.
"""

from typing import List, Literal
from typing_extensions import TypedDict
from pydantic import BaseModel, Field
from langchain_core.documents import Document


# --- Pydantic Validation Schemas for Structured Tool Calling ---

class RouteDecision(BaseModel):
    """Schema for deterministic tool routing decisions."""
    decision: Literal["metadata", "search"] = Field(
        description="Select 'metadata' for title, author, institution, or table of contents; select 'search' for technical content, equations, and results."
    )
    reasoning: str = Field(
        description="A concise 1-sentence operational justification for the chosen tool."
    )


class DecompositionPlan(BaseModel):
    """Schema for multi-hop query decomposition."""
    sub_queries: List[str] = Field(
        min_length=1,
        max_length=3,
        description="A list of 1 to 3 focused, self-contained search terms extracted from the user question."
    )


# --- LangGraph Runtime State Schema ---

class AgentState(TypedDict):
    # The original user question
    question: str

    # The router's validated decision ('metadata' or 'search')
    current_query: str

    # Operational reasoning provided by the router model
    routing_reason: str

    # Target sub-queries generated by the decomposer
    sub_queries: List[str]

    # Context chunks retrieved across all searches
    documents: List[Document]

    # Binary quality flag
    is_relevant: bool

    # Final synthesized answer
    generation: str

    # Loop guard counter
    retry_count: int